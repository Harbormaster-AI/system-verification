public class InventoryThresholdAlertService : IInventoryThresholdAlertService
{
    private readonly ApplicationTelemetry _telemetry;
    private readonly IInventoryThresholdAlertRepository _repository;
    private readonly ILogger<InventoryThresholdAlertService> _logger;
    private readonly IServiceResolver _serviceResolver;


    public InventoryThresholdAlertService(
        ApplicationTelemetry telemetry,
        IInventoryThresholdAlertRepository repository,
        ILogger<InventoryThresholdAlertService> logger,
        IServiceResolver serviceResolver)
    {
        _telemetry = telemetry;
        _repository = repository;
        _logger = logger;
        _serviceResolver = serviceResolver;
    }

    public async Task Create(InventoryThresholdAlert model, CancellationToken cancellationToken)
    {
        try
        {
            await _telemetry.Execute(
                "InventoryThresholdAlert",
                "CreateInventoryThresholdAlert",
                () => _repository.AddAsync(model, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
        }
    }

    public async Task<bool> Update(InventoryThresholdAlert model, CancellationToken cancellationToken)
    {
        try
        {
            var existing = await _repository.GetByIdAsync(model.Id, cancellationToken);
            if (existing is null)
            {
                return false;
            }
            existing.AlertNumber = model.AlertNumber;
            existing.DetectedAt = model.DetectedAt;
            existing.Message = model.Message;
            existing.AlertType = model.AlertType;
            existing.Status = model.Status;

            await _telemetry.Execute(
                "InventoryThresholdAlert",
                "UpdateInventoryThresholdAlert",
                () => _repository.UpdateAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public Task<InventoryThresholdAlert?> Get(IdentifierRequest identifier, CancellationToken cancellationToken)
    => _repository.GetByIdAsync(identifier.Id, cancellationToken);

    public Task<IReadOnlyList<InventoryThresholdAlert>> GetAll(CancellationToken cancellationToken)
    => _repository.GetAllAsync(cancellationToken);

    public async Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken)
    {
        var existing = await _repository.GetByIdAsync(identifier.Id, cancellationToken);
        if (existing is null)
        {
            return false;
        }

        try
        {
            await _telemetry.Execute(
                "InventoryThresholdAlert",
                "UpdateInventoryThresholdAlert",
                () => _repository.DeleteAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> AssignSku(AssociationRequest request, CancellationToken cancellationToken)
    {

        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No InventoryThresholdAlert found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            var childRequest = new IdentifierRequest
            {
                Id = request.ChildId,
            };

            var child = await _serviceResolver.Get<StockKeepingUnitService>().Get(childRequest, cancellationToken);
            parent.Sku = child;
            await Update(parent, cancellationToken);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> UnassignSku(AssociationRequest request, CancellationToken cancellationToken)
    {
