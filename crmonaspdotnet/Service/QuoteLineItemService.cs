}

public class QuoteLineItemService : IQuoteLineItemService
{
    private readonly ApplicationTelemetry _telemetry;
    private readonly IQuoteLineItemRepository _repository;
    private readonly ILogger<QuoteLineItemService> _logger;
    private readonly IServiceResolver _serviceResolver;


    public QuoteLineItemService(
        ApplicationTelemetry telemetry,
        IQuoteLineItemRepository repository,
        ILogger<QuoteLineItemService> logger,
        IServiceResolver serviceResolver)
    {
        _telemetry = telemetry;
        _repository = repository;
        _logger = logger;
        _serviceResolver = serviceResolver;
    }

    public async Task Create(QuoteLineItem model, CancellationToken cancellationToken)
    {
        try
        {
            await _telemetry.Execute(
                "QuoteLineItem",
                "CreateQuoteLineItem",
                () => _repository.AddAsync(model, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
        }
    }

    public async Task<bool> Update(QuoteLineItem model, CancellationToken cancellationToken)
    {
        try
        {
            var existing = await _repository.GetByIdAsync(model.Id, cancellationToken);
            if (existing is null)
            {
                return false;
            }
            existing.Quantity = model.Quantity;
            existing.UnitPrice = model.UnitPrice;
            existing.DiscountAmount = model.DiscountAmount;
            existing.TaxAmount = model.TaxAmount;
            existing.TotalAmount = model.TotalAmount;

            await _telemetry.Execute(
                "QuoteLineItem",
                "UpdateQuoteLineItem",
                () => _repository.UpdateAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public Task<QuoteLineItem?> Get(IdentifierRequest identifier, CancellationToken cancellationToken)
    => _repository.GetByIdAsync(identifier.Id, cancellationToken);

    public Task<IReadOnlyList<QuoteLineItem>> GetAll(CancellationToken cancellationToken)
    => _repository.GetAllAsync(cancellationToken);

    public async Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken)
    {
        var existing = await _repository.GetByIdAsync(identifier.Id, cancellationToken);
        if (existing is null)
        {
            return false;
        }

        try
        {
            await _telemetry.Execute(
                "QuoteLineItem",
                "UpdateQuoteLineItem",
                () => _repository.DeleteAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> AssignQuote(AssociationRequest request, CancellationToken cancellationToken)
    {

        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No QuoteLineItem found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            var childRequest = new IdentifierRequest
            {
                Id = request.ChildId,
            };

            var child = await _serviceResolver.Get<QuoteService>().Get(childRequest, cancellationToken);
            parent.Quote = child;
            await Update(parent, cancellationToken);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> UnassignQuote(AssociationRequest request, CancellationToken cancellationToken)
    {
