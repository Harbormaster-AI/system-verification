
using crmonaspdotnet.Domain;
using crmonaspdotnet.Persistence;
using crmonaspdotnet.Contracts;
using crmonaspdotnet.Telemetry;

namespace crmonaspdotnet.Service;

public interface ICampaignMemberService {

    Task Create(CampaignMember model , CancellationToken cancellationToken);
    Task<bool> Update(CampaignMember model, CancellationToken cancellationToken);
    Task<CampaignMember?> Get(IdentifierRequest identifier, CancellationToken cancellationToken);
    Task<IReadOnlyList<CampaignMember>> GetAll(CancellationToken cancellationToken);
    Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken);
    // ------------------------------
    // Single Associations
    // -------------------------------
    Task<bool> AssignCampaign(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignCampaign(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignLead(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignLead(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignContact(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignContact(AssociationRequest request, CancellationToken cancellationToken);


}

public class CampaignMemberService : ICampaignMemberService
{
    private readonly ApplicationTelemetry _telemetry;
    private readonly ICampaignMemberRepository _repository;
    private readonly ILogger<CampaignMemberService> _logger;
    private readonly IServiceResolver _serviceResolver;


    public CampaignMemberService(
        ApplicationTelemetry telemetry,
        ICampaignMemberRepository repository,
        ILogger<CampaignMemberService> logger,
        IServiceResolver serviceResolver)
    {
        _telemetry = telemetry;
        _repository = repository;
        _logger = logger;
        _serviceResolver = serviceResolver;
    }

    public async Task Create(CampaignMember model, CancellationToken cancellationToken)
    {
        try
        {
            await _telemetry.Execute(
                "CampaignMember",
                "CreateCampaignMember",
                () => _repository.AddAsync(model, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
        }
    }

    public async Task<bool> Update(CampaignMember model, CancellationToken cancellationToken)
    {
        try {
            var existing = await _repository.GetByIdAsync(model.Id, cancellationToken);
            if (existing is null)
            {
                return false;
            }
            existing.Responded = model.Responded;
            existing.Status = model.Status;
            existing.MemberType = model.MemberType;

            await _telemetry.Execute(
                "CampaignMember",
                "UpdateCampaignMember",
                () => _repository.UpdateAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public Task<CampaignMember?> Get(IdentifierRequest identifier, CancellationToken cancellationToken)
    => _repository.GetByIdAsync(identifier.Id, cancellationToken);

    public Task<IReadOnlyList<CampaignMember>> GetAll(CancellationToken cancellationToken)
    => _repository.GetAllAsync(cancellationToken);

    public async Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken)
    {
        var existing = await _repository.GetByIdAsync(identifier.Id, cancellationToken);
        if (existing is null)
        {
            return false;
        }

        try
        {
            await _telemetry.Execute(
                "CampaignMember",
                "UpdateCampaignMember",
                () => _repository.DeleteAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> AssignCampaign(AssociationRequest request, CancellationToken cancellationToken) {

        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No CampaignMember found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            var childRequest = new IdentifierRequest
            {
                Id = request.ChildId,
            };

            var child = await _serviceResolver.Get<CampaignService>().Get(childRequest, cancellationToken);
            parent.Campaign = child;
            await Update( parent, cancellationToken );
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> UnassignCampaign(AssociationRequest request, CancellationToken cancellationToken) {
        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No CampaignMember found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            parent.Campaign = null;
            await Update( parent, cancellationToken );
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

