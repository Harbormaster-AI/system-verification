
using crmonaspdotnet.Domain;
using crmonaspdotnet.Persistence;
using crmonaspdotnet.Contracts;
using crmonaspdotnet.Telemetry;

namespace crmonaspdotnet.Service;

public interface IOpportunityLineItemService
{

    Task Create(OpportunityLineItem model, CancellationToken cancellationToken);
    Task<bool> Update(OpportunityLineItem model, CancellationToken cancellationToken);
    Task<OpportunityLineItem?> Get(IdentifierRequest identifier, CancellationToken cancellationToken);
    Task<IReadOnlyList<OpportunityLineItem>> GetAll(CancellationToken cancellationToken);
    Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken);
    // ------------------------------
    // Single Associations
    // -------------------------------
    Task<bool> AssignOpportunity(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignOpportunity(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignProduct(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignProduct(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignPriceBookEntry(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignPriceBookEntry(AssociationRequest request, CancellationToken cancellationToken);


}

public class OpportunityLineItemService : IOpportunityLineItemService
{
    private readonly ApplicationTelemetry _telemetry;
    private readonly IOpportunityLineItemRepository _repository;
    private readonly ILogger<OpportunityLineItemService> _logger;
    private readonly IServiceResolver _serviceResolver;


    public OpportunityLineItemService(
        ApplicationTelemetry telemetry,
        IOpportunityLineItemRepository repository,
        ILogger<OpportunityLineItemService> logger,
        IServiceResolver serviceResolver)
    {
        _telemetry = telemetry;
        _repository = repository;
        _logger = logger;
        _serviceResolver = serviceResolver;
    }

    public async Task Create(OpportunityLineItem model, CancellationToken cancellationToken)
    {
        try
        {
            await _telemetry.Execute(
                "OpportunityLineItem",
                "CreateOpportunityLineItem",
                () => _repository.AddAsync(model, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
        }
    }

    public async Task<bool> Update(OpportunityLineItem model, CancellationToken cancellationToken)
    {
        try
        {
            var existing = await _repository.GetByIdAsync(model.Id, cancellationToken);
            if (existing is null)
            {
                return false;
            }
            existing.Quantity = model.Quantity;
            existing.UnitPrice = model.UnitPrice;
            existing.DiscountPercent = model.DiscountPercent;
            existing.TotalPrice = model.TotalPrice;

            await _telemetry.Execute(
                "OpportunityLineItem",
                "UpdateOpportunityLineItem",
                () => _repository.UpdateAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public Task<OpportunityLineItem?> Get(IdentifierRequest identifier, CancellationToken cancellationToken)
    => _repository.GetByIdAsync(identifier.Id, cancellationToken);

    public Task<IReadOnlyList<OpportunityLineItem>> GetAll(CancellationToken cancellationToken)
    => _repository.GetAllAsync(cancellationToken);

    public async Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken)
    {
        var existing = await _repository.GetByIdAsync(identifier.Id, cancellationToken);
        if (existing is null)
        {
            return false;
        }

        try
        {
            await _telemetry.Execute(
                "OpportunityLineItem",
                "UpdateOpportunityLineItem",
                () => _repository.DeleteAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> AssignOpportunity(AssociationRequest request, CancellationToken cancellationToken)
    {

        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No OpportunityLineItem found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            var childRequest = new IdentifierRequest
            {
                Id = request.ChildId,
            };

            var child = await _serviceResolver.Get<OpportunityService>().Get(childRequest, cancellationToken);
            parent.Opportunity = child;
            await Update(parent, cancellationToken);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> UnassignOpportunity(AssociationRequest request, CancellationToken cancellationToken)
    {
        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No OpportunityLineItem found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            parent.Opportunity = null;
            await Update(parent, cancellationToken);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

