using treasuryonaspdotnet.Persistence;
using treasuryonaspdotnet.Contracts;
using treasuryonaspdotnet.Telemetry;

namespace treasuryonaspdotnet.Service;

public interface ICashFlowService
{

    Task Create(CashFlow model, CancellationToken cancellationToken);
    Task<bool> Update(CashFlow model, CancellationToken cancellationToken);
    Task<CashFlow?> Get(IdentifierRequest identifier, CancellationToken cancellationToken);
    Task<IReadOnlyList<CashFlow>> GetAll(CancellationToken cancellationToken);
    Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken);
    // ------------------------------
    // Single Associations
    // -------------------------------
    Task<bool> AssignTrade(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignTrade(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignCashPosition(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignCashPosition(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignMarginCall(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignMarginCall(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignBankAccount(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignBankAccount(AssociationRequest request, CancellationToken cancellationToken);


}

public class CashFlowService : ICashFlowService
{
    private readonly ApplicationTelemetry _telemetry;
    private readonly ICashFlowRepository _repository;
    private readonly ILogger<CashFlowService> _logger;
    private readonly IServiceResolver _serviceResolver;


    public CashFlowService(
        ApplicationTelemetry telemetry,
        ICashFlowRepository repository,
        ILogger<CashFlowService> logger,
        IServiceResolver serviceResolver)
    {
        _telemetry = telemetry;
        _repository = repository;
        _logger = logger;
        _serviceResolver = serviceResolver;
    }

    public async Task Create(CashFlow model, CancellationToken cancellationToken)
    {
        try
        {
            await _telemetry.Execute(
                "CashFlow",
                "CreateCashFlow",
                () => _repository.AddAsync(model, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
        }
    }

    public async Task<bool> Update(CashFlow model, CancellationToken cancellationToken)
    {
        try
        {
            var existing = await _repository.GetByIdAsync(model.Id, cancellationToken);
            if (existing is null)
            {
                return false;
            }
            existing.FlowDate = model.FlowDate;
            existing.Amount = model.Amount;
            existing.Description = model.Description;
            existing.FlowType = model.FlowType;

            await _telemetry.Execute(
                "CashFlow",
                "UpdateCashFlow",
                () => _repository.UpdateAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public Task<CashFlow?> Get(IdentifierRequest identifier, CancellationToken cancellationToken)
    => _repository.GetByIdAsync(identifier.Id, cancellationToken);

    public Task<IReadOnlyList<CashFlow>> GetAll(CancellationToken cancellationToken)
    => _repository.GetAllAsync(cancellationToken);

    public async Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken)
    {
        var existing = await _repository.GetByIdAsync(identifier.Id, cancellationToken);
        if (existing is null)
        {
            return false;
        }

        try
        {
            await _telemetry.Execute(
                "CashFlow",
                "UpdateCashFlow",
                () => _repository.DeleteAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> AssignTrade(AssociationRequest request, CancellationToken cancellationToken)
    {

        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No CashFlow found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            var childRequest = new IdentifierRequest
            {
                Id = request.ChildId,
            };

            var child = await _serviceResolver.Get<TradeService>().Get(childRequest, cancellationToken);
            parent.Trade = child;
            await Update(parent, cancellationToken);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> UnassignTrade(AssociationRequest request, CancellationToken cancellationToken)
    {
        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No CashFlow found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            parent.Trade = null;
            await Update(parent, cancellationToken);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
