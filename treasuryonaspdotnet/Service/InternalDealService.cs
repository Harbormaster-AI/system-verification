using treasuryonaspdotnet.Telemetry;

namespace treasuryonaspdotnet.Service;

public interface IInternalDealService {

    Task Create(InternalDeal model , CancellationToken cancellationToken);
    Task<bool> Update(InternalDeal model, CancellationToken cancellationToken);
    Task<InternalDeal?> Get(IdentifierRequest identifier, CancellationToken cancellationToken);
    Task<IReadOnlyList<InternalDeal>> GetAll(CancellationToken cancellationToken);
    Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken);
    // ------------------------------
    // Single Associations
    // -------------------------------
    Task<bool> AssignTransferPricingRule(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignTransferPricingRule(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignFromUnit(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignFromUnit(AssociationRequest request, CancellationToken cancellationToken);
