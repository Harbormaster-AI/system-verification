    Task<bool> AddToCashFlows(MultipleAssociationRequest request, CancellationToken cancellationToken);
    Task<bool> RemoveFromCashFlows(MultipleAssociationRequest request, CancellationToken cancellationToken);

}

public class InternalDealService : IInternalDealService
{
    private readonly ApplicationTelemetry _telemetry;
    private readonly IInternalDealRepository _repository;
    private readonly ILogger<InternalDealService> _logger;
    private readonly IServiceResolver _serviceResolver;


    public InternalDealService(
        ApplicationTelemetry telemetry,
        IInternalDealRepository repository,
        ILogger<InternalDealService> logger,
        IServiceResolver serviceResolver)
    {
        _telemetry = telemetry;
        _repository = repository;
        _logger = logger;
        _serviceResolver = serviceResolver;
    }

    public async Task Create(InternalDeal model, CancellationToken cancellationToken)
    {
        try
        {
            await _telemetry.Execute(
                "InternalDeal",
                "CreateInternalDeal",
                () => _repository.AddAsync(model, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
        }
    }

    public async Task<bool> Update(InternalDeal model, CancellationToken cancellationToken)
    {
        try {
            var existing = await _repository.GetByIdAsync(model.Id, cancellationToken);
            if (existing is null)
            {
                return false;
            }
            existing.DealNumber = model.DealNumber;
            existing.TradeDate = model.TradeDate;
            existing.ValueDate = model.ValueDate;
            existing.MaturityDate = model.MaturityDate;
            existing.Rate = model.Rate;
            existing.Notional = model.Notional;
            existing.Product = model.Product;
            existing.Side = model.Side;
            existing.Status = model.Status;

            await _telemetry.Execute(
                "InternalDeal",
                "UpdateInternalDeal",
                () => _repository.UpdateAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public Task<InternalDeal?> Get(IdentifierRequest identifier, CancellationToken cancellationToken)
    => _repository.GetByIdAsync(identifier.Id, cancellationToken);

    public Task<IReadOnlyList<InternalDeal>> GetAll(CancellationToken cancellationToken)
    => _repository.GetAllAsync(cancellationToken);

    public async Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken)
    {
        var existing = await _repository.GetByIdAsync(identifier.Id, cancellationToken);
        if (existing is null)
        {
            return false;
        }

        try
        {
            await _telemetry.Execute(
                "InternalDeal",
                "UpdateInternalDeal",
                () => _repository.DeleteAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> AssignTransferPricingRule(AssociationRequest request, CancellationToken cancellationToken) {

        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No InternalDeal found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            var childRequest = new IdentifierRequest
            {
                Id = request.ChildId,
            };

            var child = await _serviceResolver.Get<TransferPricingRuleService>().Get(childRequest, cancellationToken);
            parent.TransferPricingRule = child;
            await Update( parent, cancellationToken );
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> UnassignTransferPricingRule(AssociationRequest request, CancellationToken cancellationToken) {
