
using treasuryonaspdotnet.Domain;
using treasuryonaspdotnet.Persistence;
using treasuryonaspdotnet.Contracts;
using treasuryonaspdotnet.Telemetry;

namespace treasuryonaspdotnet.Service;

public interface IAccountingEntryService
{

    Task Create(AccountingEntry model, CancellationToken cancellationToken);
    Task<bool> Update(AccountingEntry model, CancellationToken cancellationToken);
    Task<AccountingEntry?> Get(IdentifierRequest identifier, CancellationToken cancellationToken);
    Task<IReadOnlyList<AccountingEntry>> GetAll(CancellationToken cancellationToken);
    Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken);
    // ------------------------------
    // Single Associations
    // -------------------------------
    Task<bool> AssignTrade(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignTrade(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignHedgeRelationship(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignHedgeRelationship(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> AssignPortfolio(AssociationRequest request, CancellationToken cancellationToken);
    Task<bool> UnassignPortfolio(AssociationRequest request, CancellationToken cancellationToken);


}

public class AccountingEntryService : IAccountingEntryService
{
    private readonly ApplicationTelemetry _telemetry;
    private readonly IAccountingEntryRepository _repository;
    private readonly ILogger<AccountingEntryService> _logger;
    private readonly IServiceResolver _serviceResolver;


    public AccountingEntryService(
        ApplicationTelemetry telemetry,
        IAccountingEntryRepository repository,
        ILogger<AccountingEntryService> logger,
        IServiceResolver serviceResolver)
    {
        _telemetry = telemetry;
        _repository = repository;
        _logger = logger;
        _serviceResolver = serviceResolver;
    }

    public async Task Create(AccountingEntry model, CancellationToken cancellationToken)
    {
        try
        {
            await _telemetry.Execute(
                "AccountingEntry",
                "CreateAccountingEntry",
                () => _repository.AddAsync(model, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
        }
    }

    public async Task<bool> Update(AccountingEntry model, CancellationToken cancellationToken)
    {
        try
        {
            var existing = await _repository.GetByIdAsync(model.Id, cancellationToken);
            if (existing is null)
            {
                return false;
            }
            existing.PostingDate = model.PostingDate;
            existing.Account = model.Account;
            existing.Amount = model.Amount;
            existing.Narrative = model.Narrative;
            existing.Treatment = model.Treatment;

            await _telemetry.Execute(
                "AccountingEntry",
                "UpdateAccountingEntry",
                () => _repository.UpdateAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public Task<AccountingEntry?> Get(IdentifierRequest identifier, CancellationToken cancellationToken)
    => _repository.GetByIdAsync(identifier.Id, cancellationToken);

    public Task<IReadOnlyList<AccountingEntry>> GetAll(CancellationToken cancellationToken)
    => _repository.GetAllAsync(cancellationToken);

    public async Task<bool> Delete(IdentifierRequest identifier, CancellationToken cancellationToken)
    {
        var existing = await _repository.GetByIdAsync(identifier.Id, cancellationToken);
        if (existing is null)
        {
            return false;
        }

        try
        {
            await _telemetry.Execute(
                "AccountingEntry",
                "UpdateAccountingEntry",
                () => _repository.DeleteAsync(existing, cancellationToken));
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> AssignTrade(AssociationRequest request, CancellationToken cancellationToken)
    {

        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No AccountingEntry found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            var childRequest = new IdentifierRequest
            {
                Id = request.ChildId,
            };

            var child = await _serviceResolver.Get<TradeService>().Get(childRequest, cancellationToken);
            parent.Trade = child;
            await Update(parent, cancellationToken);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

    public async Task<bool> UnassignTrade(AssociationRequest request, CancellationToken cancellationToken)
    {
        var parent = await _repository.GetByIdAsync(request.ParentId, cancellationToken);
        if (parent is null)
        {
            _logger.LogError("No AccountingEntry found using Id {ParentId}", request.ParentId);
            return false;
        }

        try
        {
            parent.Trade = null;
            await Update(parent, cancellationToken);
        }
        catch (Exception ex)
        {
            _logger.LogError(
                    ex,
                    "Unexpected error while creating Transaction.");
            return false;
        }
        return true;
    }

